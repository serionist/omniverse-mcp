GOOD_SKILL = """---
name: start-work
description: >-
  Use when someone wants to work on something: finds the issue,
  writes the plan.
---

# Start a change
"""


def message(line: str) -> str:
    return f"Fix the capture's lighting\n\nWhy it changed.\n\n{line}\nRefs #2\n"


# Attribution


@pytest.mark.parametrize("line", REFUSED)
def test_each_attribution_form_is_found(line):
    assert gate.attribution_lines(message(line)) == [line.strip()]


@pytest.mark.parametrize("line", ALLOWED)
def test_text_without_attribution_passes(line):
    assert gate.attribution_lines(message(line)) == []


