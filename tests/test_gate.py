@pytest.mark.parametrize("char", ["#", ";"])
def test_commit_msg_reads_comment_lines_but_not_the_diff_below_the_scissors(tmp_path, char):
    # With -m git keeps comment lines in the message; the diff `git commit -v` adds below the scissors never reaches
    # the commit, and a diff of this file's REFUSED list must not refuse the commit that changes it.
    diff = "\n".join(f'+    "{line}",' for line in REFUSED)
    below = (
        f"{char} ------------------------ >8 ------------------------\n"
        f"{char} Do not modify or remove the line above.\n"
        f"{char} Everything below it will be ignored.\n"
        "diff --git a/tests/test_gate.py b/tests/test_gate.py\n"
        f"{diff}\n"
    )
    template = GIT_TEMPLATE.replace("\n#", f"\n{char}")
    assert commit_msg(tmp_path, template + below) == 0
    assert commit_msg(tmp_path, f"{template}{char} Generated with Claude Code\n{below}") == 1
    assert hooks.message_text(template + below) == template.strip()


